#!/usr/bin/env python3
"""Generate the pass-1 W-mode body proofs of the windows avx_x4 kernel.

The windows pilot `Hashtree/Gen/WinAvxX4P` checks the kernel at count 4 from `entrySW 24`;
`Hashtree/Proofs/WinAvxX4WShift.shiftKW` rebases its cuts on the wrapper call state
`WinWrapper.entryWin`.  This emits

  Hashtree/Proofs/WinAvxX4WBodyP{1..4}.lean   the 201 body slices 2..202 re-checked at the
                                               rebased cuts (`decide +kernel`), four files
  Hashtree/Proofs/WinAvxX4WBody.lean           the environment chain and `body_runW`
                                               (`K2 -> K203`, every count `c >= 4`)

Usage:  python3 tools/winx4w.py [--pass2]   (--pass2 emits the later-pass files
        WinAvxX4WBodyS* on the stripped cuts, see WinAvxX4WStripDefs)
"""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, "Hashtree", "Gen", "WinAvxX4P")
PROOFS = os.path.join(ROOT, "Hashtree", "Proofs")
FIRST, LAST, PARTS = 2, 202, 4
HEADER = """set_option maxRecDepth 200000
set_option maxHeartbeats 0
set_option linter.unusedVariables false
set_option linter.unusedSimpArgs false

open Hashtree.Asm Hashtree.Asm.X86 Hashtree.Asm.X86Sym Hashtree.Asm.X86SymW
open Hashtree.Kernels.X86Win.AvxX4
open Hashtree.Gen.WinAvxX4P
open Hashtree.Proofs.WinAvxX4W
"""

def read_slices():
    pat = re.compile(r"theorem slice(\d+) : sliceCheck prog 4 m0q \(fun pc => decide \(pc ∈ "
                     r"\((\[[0-9, ]*\]) : List Nat\)\)\) (\d+) K(\d+) K(\d+) T(\d+)")
    slices = {}
    for name in os.listdir(GEN):
        if name.startswith("P") and name.endswith(".lean"):
            for m in pat.finditer(open(os.path.join(GEN, name)).read()):
                j = int(m.group(1))
                slices[j] = dict(orc=m.group(2), n=int(m.group(3)), k0=int(m.group(4)),
                                 k1=int(m.group(5)), t=int(m.group(6)))
    for j in range(FIRST, LAST + 1):
        s = slices[j]
        assert s["k0"] == j and s["k1"] == j + 1 and s["t"] == j, (j, s)
    return slices

def orc(s):
    return f"(fun pc => decide (pc ∈ ({s['orc']} : List Nat)))"

def rsum(ns):
    return str(ns[0]) if len(ns) == 1 else "%d + (%s)" % (ns[0], rsum(ns[1:]))

def part_ranges():
    n = LAST - FIRST + 1; per = (n + PARTS - 1) // PARTS
    out, j = [], FIRST
    while j <= LAST:
        out.append((j, min(j + per - 1, LAST))); j += per
    return out

def emit_part(p, lo, hi, slices):
    a = ["import Hashtree.Proofs.WinAvxX4WShift"]
    for j in range(lo - 1, hi + 1):
        a.append(f"import Hashtree.Gen.WinAvxX4P.D{j}")
    a.append(HEADER)
    a.append(f"/-! The windows avx_x4 body slices {lo}..{hi} at the wrapper call state"
             f" (generated by tools/winx4w.py). -/")
    a.append("namespace Hashtree.Proofs.WinAvxX4WBody\n")
    for j in range(lo, hi + 1):
        s = slices[j]
        a.append(f"theorem sliceW_{j} : sliceCheck prog 4 m0W {orc(s)} {s['n']} (shiftKW K{j}) "
                 f"(shiftKW K{j + 1}) T{j} = true := by\n  decide +kernel\n")
    a.append("end Hashtree.Proofs.WinAvxX4WBody\n")
    return "\n".join(a)

def emit_main(ranges, slices):
    a = [f"import Hashtree.Proofs.WinAvxX4WBodyP{p + 1}" for p in range(len(ranges))]
    a.append(HEADER)
    a.append("""/-!
# The windows avx_x4 body at the wrapper call state, every count

The pilot's 201 body slices `K2 .. K203` re-checked at the cuts rebased by `shiftKW`
(`WinAvxX4WBodyP1..P4`, generated by `tools/winx4w.py`) and composed: `body_runW` runs from
the rebased `K2` to the rebased `K203` at any count `c = σ 2 ≥ 4`, using only the pilot's two
entry conditions (`A0`); `body_memW` carries the memory relation.  The two slices with the
inner `jb` taken (51, 83) keep the pilot's oracle; their conditions are decided on the round
counter and record nothing.
-/""")
    a.append("namespace Hashtree.Proofs.WinAvxX4WBody\n")
    a.append(f"def G{FIRST} (env1 : Key → W32) : Key → W32 := env1")
    for j in range(FIRST, LAST + 1):
        s = slices[j]
        a.append(f"def G{j + 1} (env1 : Key → W32) : Key → W32 := "
                 f"envAbs (G{j} env1) (run prog 4 m0W {orc(s)} {s['n']} (shiftKW K{j}))")
    nums = [slices[j]["n"] for j in range(FIRST, LAST + 1)]
    total = rsum(nums)
    a.append(f"""
/-- The body's instruction count ({sum(nums)}). -/
def BODYLEN : Nat := {total}

/-- **The body at the wrapper call state, every count `c ≥ 4`.** -/
theorem body_runW (env1 : Key → W32) (σ : Nat → Int) (mem0c : Addr Int → Cell W32 Int)
    (orcC : Nat → Bool) (h0 : Mem0Rel (G{FIRST} env1) σ m0W mem0c) (hge : 4 ≤ σ 2) :
    run prog 4 mem0c orcC BODYLEN (mapState (G{FIRST} env1) σ (shiftKW K{FIRST})) =
      mapState (G{LAST + 1} env1) σ (shiftKW K{LAST + 1}) := by
  unfold BODYLEN
  have kq : MemKeyed m0W := m0W_keyed
  have hm{FIRST} : Mem0Rel (G{FIRST} env1) σ m0W mem0c := h0""")
    for j in range(FIRST, LAST + 1):
        a.append(f"  have hm{j + 1} : Mem0Rel (G{j + 1} env1) σ m0W mem0c := "
                 f"mem0Rel_envAbs _ σ _ mem0c kq hm{j} _")
    for j in range(FIRST, LAST + 1):
        s = slices[j]
        a.append(f"  have r{j} : run prog 4 mem0c orcC {s['n']} (mapState (G{j} env1) σ (shiftKW K{j})) = "
                 f"mapState (G{j + 1} env1) σ (shiftKW K{j + 1}) := "
                 f"(slice_sound (G{j} env1) σ m0W mem0c hm{j} prog 4 {orc(s)} orcC {s['n']} (shiftKW K{j}) "
                 f"(shiftKW K{j + 1}) T{j} sliceW_{j} rfl "
                 f"(assumeOk_of σ (shiftKW K{j + 1}) A0 rfl (asmge σ hge))).1")
    for j in range(FIRST, LAST):
        a.append(f"  rw [run_add, r{j}]")
    a.append(f"  exact r{LAST}\n")
    a.append(f"""/-- The memory relation carried along the body. -/
theorem body_memW (env1 : Key → W32) (σ : Nat → Int) (mem0c : Addr Int → Cell W32 Int)
    (h0 : Mem0Rel (G{FIRST} env1) σ m0W mem0c) : Mem0Rel (G{LAST + 1} env1) σ m0W mem0c := by
  have kq : MemKeyed m0W := m0W_keyed
  have hm{FIRST} : Mem0Rel (G{FIRST} env1) σ m0W mem0c := h0""")
    for j in range(FIRST, LAST + 1):
        a.append(f"  have hm{j + 1} : Mem0Rel (G{j + 1} env1) σ m0W mem0c := "
                 f"mem0Rel_envAbs _ σ _ mem0c kq hm{j} _")
    a.append(f"  exact hm{LAST + 1}\n")
    a.append("end Hashtree.Proofs.WinAvxX4WBody\n")
    return "\n".join(a)

def emit_part2(p, lo, hi, slices):
    a = ["import Hashtree.Proofs.WinAvxX4WStripDefs"]
    for j in range(lo - 1, hi + 1):
        a.append(f"import Hashtree.Gen.WinAvxX4P.D{j}")
    a.append(HEADER)
    a.append("open Hashtree.Proofs.WinAvxX4WStrip\n")
    a.append(f"/-! The windows avx_x4 body slices {lo}..{hi} of a later pass (saved bytes stripped,"
             f" served from the push list) (generated by tools/winx4w.py --pass2). -/")
    a.append("namespace Hashtree.Proofs.WinAvxX4WBodyS\n")
    for j in range(lo, hi + 1):
        s = slices[j]
        a.append(f"theorem sliceS_{j} : sliceCheck prog 4 m0WP {orc(s)} {s['n']} (stripKW K{j}) "
                 f"(stripKW K{j + 1}) T{j} = true := by\n  decide +kernel\n")
    a.append("end Hashtree.Proofs.WinAvxX4WBodyS\n")
    return "\n".join(a)

def emit_main2(ranges, slices):
    a = [f"import Hashtree.Proofs.WinAvxX4WBodyS{p + 1}" for p in range(len(ranges))]
    a.append("import Hashtree.Proofs.WinAvxX4WStrip")
    a.append("import Hashtree.Proofs.WinAvxX4WBody")
    a.append(HEADER)
    a.append("open Hashtree.Proofs.WinAvxX4WStrip")
    a.append("open Hashtree.Proofs.WinAvxX4WBody (BODYLEN)\n")
    a.append("""/-!
# The windows avx_x4 body of a later pass

The 201 body slices `K2 .. K203` of a second or later pass: the cuts are stripped of the 160
saved bytes (`stripKW`), which the symbolic memory `m0WP` serves from its push list; the first
two cuts carry the loop-carried vector registers (`KHs`, `KH3s`; `WinAvxX4WStrip.stripFacts`:
`sliceV2s`, `sliceV3s`).  `bodyS_runW` composes them from the stripped invariant head to the
stripped `K203` (generated by `tools/winx4w.py --pass2`).
-/""")
    a.append("namespace Hashtree.Proofs.WinAvxX4WBodyS\n")
    a.append("/-- The two replayed head cuts, read off the kernel check. -/")
    a.append(f"theorem sliceV2s : sliceCheck prog 4 m0WP orcB {slices[2]['n']} KHs KH3s T2 = true :=")
    a.append("  (stripFacts stripOk_true).2.1")
    a.append(f"theorem sliceV3s : sliceCheck prog 4 m0WP orcB {slices[3]['n']} KH3s (stripKW K4) T3 = true :=")
    a.append("  (stripFacts stripOk_true).2.2.1\n")
    a.append("/-! ## The environment chain of a later pass -/\n")
    a.append(f"def GS{FIRST} (env1 : Key → W32) : Key → W32 := env1")
    a.append(f"def GS3 (env1 : Key → W32) : Key → W32 := "
             f"envAbs (GS2 env1) (run prog 4 m0WP orcB {slices[2]['n']} KHs)")
    a.append(f"def GS4 (env1 : Key → W32) : Key → W32 := "
             f"envAbs (GS3 env1) (run prog 4 m0WP orcB {slices[3]['n']} KH3s)")
    for j in range(4, LAST + 1):
        s = slices[j]
        a.append(f"def GS{j + 1} (env1 : Key → W32) : Key → W32 := "
                 f"envAbs (GS{j} env1) (run prog 4 m0WP {orc(s)} {s['n']} (stripKW K{j}))")
    a.append("")
    nums = [slices[j]["n"] for j in range(FIRST, LAST + 1)]
    total = rsum(nums)
    a.append(f"""/-- **A later pass of the body.**  From the stripped invariant head to the stripped `K203`,
`BODYLEN` instructions, at any count `c ≥ 4`, over the push memory. -/
theorem bodyS_runW (env1 : Key → W32) (σ : Nat → Int) (mem0c : Addr Int → Cell W32 Int)
    (orcC : Nat → Bool) (h0 : Mem0Rel (GS{FIRST} env1) σ m0WP mem0c) (hge : 4 ≤ σ 2) :
    run prog 4 mem0c orcC BODYLEN (mapState (GS{FIRST} env1) σ KHs) =
      mapState (GS{LAST + 1} env1) σ (stripKW K{LAST + 1}) := by
  rw [show BODYLEN = ({total}) from rfl]
  have kq : MemKeyed m0WP := m0WP_keyed
  have hm{FIRST} : Mem0Rel (GS{FIRST} env1) σ m0WP mem0c := h0""")
    for j in range(FIRST, LAST + 1):
        a.append(f"  have hm{j + 1} : Mem0Rel (GS{j + 1} env1) σ m0WP mem0c := "
                 f"mem0Rel_envAbs _ σ _ mem0c kq hm{j} _")
    a.append(f"  have r2 : run prog 4 mem0c orcC {slices[2]['n']} (mapState (GS2 env1) σ KHs) = "
             f"mapState (GS3 env1) σ KH3s := "
             f"(slice_sound (GS2 env1) σ m0WP mem0c hm2 prog 4 orcB orcC {slices[2]['n']} KHs KH3s T2 "
             f"sliceV2s rfl (assumeOk_of σ KH3s A0 rfl (asmge σ hge))).1")
    a.append(f"  have r3 : run prog 4 mem0c orcC {slices[3]['n']} (mapState (GS3 env1) σ KH3s) = "
             f"mapState (GS4 env1) σ (stripKW K4) := "
             f"(slice_sound (GS3 env1) σ m0WP mem0c hm3 prog 4 orcB orcC {slices[3]['n']} KH3s (stripKW K4) T3 "
             f"sliceV3s rfl (assumeOk_of σ (stripKW K4) A0 rfl (asmge σ hge))).1")
    for j in range(4, LAST + 1):
        s = slices[j]
        a.append(f"  have r{j} : run prog 4 mem0c orcC {s['n']} (mapState (GS{j} env1) σ (stripKW K{j})) = "
                 f"mapState (GS{j + 1} env1) σ (stripKW K{j + 1}) := "
                 f"(slice_sound (GS{j} env1) σ m0WP mem0c hm{j} prog 4 {orc(s)} orcC {s['n']} (stripKW K{j}) "
                 f"(stripKW K{j + 1}) T{j} sliceS_{j} rfl "
                 f"(assumeOk_of σ (stripKW K{j + 1}) A0 rfl (asmge σ hge))).1")
    for j in range(FIRST, LAST):
        a.append(f"  rw [run_add, r{j}]")
    a.append(f"  exact r{LAST}\n")
    a.append(f"""/-- The memory relation carried along a later pass. -/
theorem bodyS_memW (env1 : Key → W32) (σ : Nat → Int) (mem0c : Addr Int → Cell W32 Int)
    (h0 : Mem0Rel (GS{FIRST} env1) σ m0WP mem0c) : Mem0Rel (GS{LAST + 1} env1) σ m0WP mem0c := by
  have kq : MemKeyed m0WP := m0WP_keyed
  have hm{FIRST} : Mem0Rel (GS{FIRST} env1) σ m0WP mem0c := h0""")
    for j in range(FIRST, LAST + 1):
        a.append(f"  have hm{j + 1} : Mem0Rel (GS{j + 1} env1) σ m0WP mem0c := "
                 f"mem0Rel_envAbs _ σ _ mem0c kq hm{j} _")
    a.append(f"  exact hm{LAST + 1}\n")
    a.append("end Hashtree.Proofs.WinAvxX4WBodyS\n")
    return "\n".join(a)

def main():
    slices = read_slices(); ranges = part_ranges()
    if len(sys.argv) == 2 and sys.argv[1] == "--pass2":
        ranges = [(max(lo, 4), hi) for (lo, hi) in ranges]
        for p, (lo, hi) in enumerate(ranges):
            path = os.path.join(PROOFS, f"WinAvxX4WBodyS{p + 1}.lean")
            open(path, "w").write(emit_part2(p, lo, hi, slices)); print("wrote", path, lo, hi)
        path = os.path.join(PROOFS, "WinAvxX4WBodyS.lean")
        open(path, "w").write(emit_main2(ranges, slices)); print("wrote", path)
        return
    for p, (lo, hi) in enumerate(ranges):
        path = os.path.join(PROOFS, f"WinAvxX4WBodyP{p + 1}.lean")
        open(path, "w").write(emit_part(p, lo, hi, slices)); print("wrote", path, lo, hi)
    path = os.path.join(PROOFS, "WinAvxX4WBody.lean")
    open(path, "w").write(emit_main(ranges, slices)); print("wrote", path)

if __name__ == "__main__":
    main()
