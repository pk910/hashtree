#!/usr/bin/env python3
"""Generate the W-mode (wrapper call state) body proofs of the avx2_x8 kernel, per residue.

The pilot `Hashtree/Gen/Avx2X8P` checks the kernel at count 8 from `entryS 24`.  At the
wrapper's call state the frame sits at the alignment residue `r = (σ 9 - 8) % 32`
(`Hashtree/Proofs/Avx2X8Align`), and `Hashtree/Proofs/Avx2X8WShift.shiftK8 r` rebases a pilot
cut on it.  This script emits, for one residue `r`:

  Hashtree/Proofs/Avx2X8WBodyR{r}P{1..4}.lean   the 208 body slices 2..209 re-checked at the
                                                 rebased cuts (`decide +kernel`), four files so
                                                 that `lake build` checks them in parallel
  Hashtree/Proofs/Avx2X8WBodyR{r}.lean           the environment chains and the composed body
                                                 runs: `body_runW` (the first pass, from the
                                                 rebased `K2`) and `bodyV_runW` (every later
                                                 pass, from the loop head `KH r`)

Usage:  python3 tools/avx_x8w.py <r> [--pass2]   (r = 0 or 16, the residues the wrapper ABI
        allows; --pass2 emits the later-pass files Avx2X8WBodyR{r}S* on the stripped cuts)

The slice lengths and tree lists are read from the committed pilot files; no new `decide`
is introduced beyond the per-slice re-checks.
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, "Hashtree", "Gen", "Avx2X8P")
PROOFS = os.path.join(ROOT, "Hashtree", "Proofs")

HEADER = """set_option maxRecDepth 200000
set_option maxHeartbeats 0
set_option linter.unusedVariables false
set_option linter.unusedSimpArgs false

open Hashtree.Asm Hashtree.Asm.X86 Hashtree.Asm.X86Sym Hashtree.Asm.X86SymW
open Hashtree.Kernels.X86.Avx2X8
open Hashtree.Gen.Avx2X8P
open Hashtree.Proofs.Avx2X8Align
open Hashtree.Proofs.Avx2X8WShift
"""

FIRST, LAST = 2, 209          # body slices K2 -> K210
PARTS = 4


def read_slices():
    pat = re.compile(r"theorem slice(\d+) : sliceCheck prog 4 m0q \(fun pc => decide \(pc ∈ "
                     r"\((\[[0-9, ]*\]) : List Nat\)\)\) (\d+) K(\d+) K(\d+) T(\d+)")
    slices = {}
    for name in os.listdir(GEN):
        if not (name.startswith("P") and name.endswith(".lean")):
            continue
        for m in pat.finditer(open(os.path.join(GEN, name)).read()):
            j = int(m.group(1))
            slices[j] = dict(orc=m.group(2), n=int(m.group(3)), k0=int(m.group(4)),
                             k1=int(m.group(5)), t=int(m.group(6)))
    for j in range(FIRST, LAST + 1):
        s = slices[j]
        assert s["orc"] == "[]" and s["k0"] == j and s["k1"] == j + 1 and s["t"] == j, (j, s)
    return slices


def rsum(ns):
    if len(ns) == 1:
        return str(ns[0])
    return "%d + (%s)" % (ns[0], rsum(ns[1:]))


def part_ranges():
    n = LAST - FIRST + 1
    per = (n + PARTS - 1) // PARTS
    out = []
    j = FIRST
    while j <= LAST:
        out.append((j, min(j + per - 1, LAST)))
        j += per
    return out


def emit_part(r, p, lo, hi, slices):
    a = []
    a.append("import Hashtree.Proofs.Avx2X8WShift")
    for j in range(lo - 1, hi + 1):      # D_{j-1} holds K_j, D_j holds K_{j+1} and T_j
        a.append(f"import Hashtree.Gen.Avx2X8P.D{j}")
    a.append(HEADER)
    a.append(f"/-! The avx2_x8 body slices {lo}..{hi} at the wrapper call state, residue {r}"
             f" (generated by tools/avx_x8w.py). -/")
    a.append(f"namespace Hashtree.Proofs.Avx2X8WBodyR{r}\n")
    for j in range(lo, hi + 1):
        s = slices[j]
        a.append(f"theorem sliceW_{j} : sliceCheck prog 4 m8 orcB {s['n']} (shiftK8 {r} K{j}) "
                 f"(shiftK8 {r} K{j + 1}) T{j} = true := by\n  decide +kernel\n")
    a.append(f"end Hashtree.Proofs.Avx2X8WBodyR{r}\n")
    return "\n".join(a)


def emit_main(r, ranges, slices):
    a = []
    for p in range(len(ranges)):
        a.append(f"import Hashtree.Proofs.Avx2X8WBodyR{r}P{p + 1}")
    a.append(HEADER)
    a.append(f"""/-!
# The avx2_x8 body at the wrapper call state, residue {r}

The pilot's 208 branch-free body slices `K2 .. K210` (6035 instructions) re-checked at the
cuts rebased by `shiftK8 {r}` (the parts `P1..P4`, generated by `tools/avx_x8w.py`), and
composed:

* `body_runW`: the first pass, from the rebased `K2` reached by the entry
  (`Avx2X8WShift.sliceE_{r}`), at any count `c = σ 2 ≥ 8`;
* `bodyV_runW`: every later pass, from the loop invariant head `KH {r}` through the two
  replayed cuts (`sliceV2_{r}`, `sliceV3_{r}`) and then the pass-1 cuts from `K4` on.

Both use only the pilot's two entry conditions (`A0`: `c < 8` false, `c ≠ 0` true).
-/""")
    a.append(f"namespace Hashtree.Proofs.Avx2X8WBodyR{r}\n")
    # env chain, pass 1
    a.append("/-! ## The environment chain of the first pass -/\n")
    a.append(f"def G{FIRST} (env1 : Key → W32) : Key → W32 := env1")
    for j in range(FIRST, LAST + 1):
        s = slices[j]
        a.append(f"def G{j + 1} (env1 : Key → W32) : Key → W32 := "
                 f"envAbs (G{j} env1) (run prog 4 m8 orcB {s['n']} (shiftK8 {r} K{j}))")
    a.append("")
    # env chain, later passes
    a.append("/-! ## The environment chain of a later pass (from the loop head) -/\n")
    a.append(f"def GV{FIRST} (env1 : Key → W32) : Key → W32 := env1")
    a.append(f"def GV3 (env1 : Key → W32) : Key → W32 := "
             f"envAbs (GV2 env1) (run prog 4 m8 orcB {slices[2]['n']} (KH {r}))")
    a.append(f"def GV4 (env1 : Key → W32) : Key → W32 := "
             f"envAbs (GV3 env1) (run prog 4 m8 orcB {slices[3]['n']} (KH3 {r}))")
    for j in range(4, LAST + 1):
        s = slices[j]
        a.append(f"def GV{j + 1} (env1 : Key → W32) : Key → W32 := "
                 f"envAbs (GV{j} env1) (run prog 4 m8 orcB {s['n']} (shiftK8 {r} K{j}))")
    a.append("")
    nums = [slices[j]["n"] for j in range(FIRST, LAST + 1)]
    total = rsum(nums)
    # body_runW
    a.append(f"""/-- **The first pass of the body, residue {r}.**  From the rebased `K2` to the rebased
`K210`, 6035 instructions, at any count `c ≥ 8`. -/
theorem body_runW (env1 : Key → W32) (σ : Nat → Int) (mem0c : Addr Int → Cell W32 Int)
    (orcC : Nat → Bool) (h0 : Mem0Rel (G{FIRST} env1) σ m8 mem0c) (hge : 8 ≤ σ 2) :
    run prog 4 mem0c orcC ({total}) (mapState (G{FIRST} env1) σ (shiftK8 {r} K{FIRST})) =
      mapState (G{LAST + 1} env1) σ (shiftK8 {r} K{LAST + 1}) := by
  have kq : MemKeyed m8 := m8_keyed
  have hm{FIRST} : Mem0Rel (G{FIRST} env1) σ m8 mem0c := h0""")
    for j in range(FIRST, LAST + 1):
        a.append(f"  have hm{j + 1} : Mem0Rel (G{j + 1} env1) σ m8 mem0c := "
                 f"mem0Rel_envAbs _ σ _ mem0c kq hm{j} _")
    for j in range(FIRST, LAST + 1):
        s = slices[j]
        a.append(f"  have r{j} : run prog 4 mem0c orcC {s['n']} (mapState (G{j} env1) σ (shiftK8 {r} K{j})) = "
                 f"mapState (G{j + 1} env1) σ (shiftK8 {r} K{j + 1}) := "
                 f"(slice_sound (G{j} env1) σ m8 mem0c hm{j} prog 4 orcB orcC {s['n']} (shiftK8 {r} K{j}) "
                 f"(shiftK8 {r} K{j + 1}) T{j} sliceW_{j} rfl "
                 f"(assumeOk_of σ (shiftK8 {r} K{j + 1}) A0 rfl (asmge σ hge))).1")
    for j in range(FIRST, LAST):
        a.append(f"  rw [run_add, r{j}]")
    a.append(f"  exact r{LAST}\n")
    # body_memW
    a.append(f"""/-- The memory relation carried along the first pass. -/
theorem body_memW (env1 : Key → W32) (σ : Nat → Int) (mem0c : Addr Int → Cell W32 Int)
    (h0 : Mem0Rel (G{FIRST} env1) σ m8 mem0c) : Mem0Rel (G{LAST + 1} env1) σ m8 mem0c := by
  have kq : MemKeyed m8 := m8_keyed
  have hm{FIRST} : Mem0Rel (G{FIRST} env1) σ m8 mem0c := h0""")
    for j in range(FIRST, LAST + 1):
        a.append(f"  have hm{j + 1} : Mem0Rel (G{j + 1} env1) σ m8 mem0c := "
                 f"mem0Rel_envAbs _ σ _ mem0c kq hm{j} _")
    a.append(f"  exact hm{LAST + 1}\n")
    # bodyV_runW
    a.append(f"""/-- **A later pass of the body, residue {r}.**  From the loop invariant head `KH {r}`
(the rebased `K2` with the loop-carried `ymm2..15`) to the rebased `K210`: the two replayed
cuts, then the pass-1 cuts. -/
theorem bodyV_runW (env1 : Key → W32) (σ : Nat → Int) (mem0c : Addr Int → Cell W32 Int)
    (orcC : Nat → Bool) (h0 : Mem0Rel (GV{FIRST} env1) σ m8 mem0c) (hge : 8 ≤ σ 2) :
    run prog 4 mem0c orcC ({total}) (mapState (GV{FIRST} env1) σ (KH {r})) =
      mapState (GV{LAST + 1} env1) σ (shiftK8 {r} K{LAST + 1}) := by
  have kq : MemKeyed m8 := m8_keyed
  have hm{FIRST} : Mem0Rel (GV{FIRST} env1) σ m8 mem0c := h0""")
    for j in range(FIRST, LAST + 1):
        a.append(f"  have hm{j + 1} : Mem0Rel (GV{j + 1} env1) σ m8 mem0c := "
                 f"mem0Rel_envAbs _ σ _ mem0c kq hm{j} _")
    a.append(f"  have r2 : run prog 4 mem0c orcC {slices[2]['n']} (mapState (GV2 env1) σ (KH {r})) = "
             f"mapState (GV3 env1) σ (KH3 {r}) := "
             f"(slice_sound (GV2 env1) σ m8 mem0c hm2 prog 4 orcB orcC {slices[2]['n']} (KH {r}) (KH3 {r}) T2 "
             f"sliceV2_{r} rfl (assumeOk_of σ (KH3 {r}) A0 rfl (asmge σ hge))).1")
    a.append(f"  have r3 : run prog 4 mem0c orcC {slices[3]['n']} (mapState (GV3 env1) σ (KH3 {r})) = "
             f"mapState (GV4 env1) σ (shiftK8 {r} K4) := "
             f"(slice_sound (GV3 env1) σ m8 mem0c hm3 prog 4 orcB orcC {slices[3]['n']} (KH3 {r}) (shiftK8 {r} K4) T3 "
             f"sliceV3_{r} rfl (assumeOk_of σ (shiftK8 {r} K4) A0 rfl (asmge σ hge))).1")
    for j in range(4, LAST + 1):
        s = slices[j]
        a.append(f"  have r{j} : run prog 4 mem0c orcC {s['n']} (mapState (GV{j} env1) σ (shiftK8 {r} K{j})) = "
                 f"mapState (GV{j + 1} env1) σ (shiftK8 {r} K{j + 1}) := "
                 f"(slice_sound (GV{j} env1) σ m8 mem0c hm{j} prog 4 orcB orcC {s['n']} (shiftK8 {r} K{j}) "
                 f"(shiftK8 {r} K{j + 1}) T{j} sliceW_{j} rfl "
                 f"(assumeOk_of σ (shiftK8 {r} K{j + 1}) A0 rfl (asmge σ hge))).1")
    for j in range(FIRST, LAST):
        a.append(f"  rw [run_add, r{j}]")
    a.append(f"  exact r{LAST}\n")
    a.append(f"""/-- The memory relation carried along a later pass. -/
theorem bodyV_memW (env1 : Key → W32) (σ : Nat → Int) (mem0c : Addr Int → Cell W32 Int)
    (h0 : Mem0Rel (GV{FIRST} env1) σ m8 mem0c) : Mem0Rel (GV{LAST + 1} env1) σ m8 mem0c := by
  have kq : MemKeyed m8 := m8_keyed
  have hm{FIRST} : Mem0Rel (GV{FIRST} env1) σ m8 mem0c := h0""")
    for j in range(FIRST, LAST + 1):
        a.append(f"  have hm{j + 1} : Mem0Rel (GV{j + 1} env1) σ m8 mem0c := "
                 f"mem0Rel_envAbs _ σ _ mem0c kq hm{j} _")
    a.append(f"  exact hm{LAST + 1}\n")
    a.append(f"/-- The body's instruction count. -/\ndef BODYLEN : Nat := {total}\n")
    a.append(f"end Hashtree.Proofs.Avx2X8WBodyR{r}\n")
    return "\n".join(a)


def emit_part2(r, p, lo, hi, slices):
    a = []
    a.append("import Hashtree.Proofs.Avx2X8WStripDefs")
    for j in range(lo - 1, hi + 1):
        a.append(f"import Hashtree.Gen.Avx2X8P.D{j}")
    a.append(HEADER)
    a.append("open Hashtree.Proofs.Avx2X8WStrip\n")
    a.append(f"/-! The avx2_x8 body slices {lo}..{hi} of a later pass (spilled cells stripped, served"
             f" from the push list), residue {r} (generated by tools/avx_x8w.py). -/")
    a.append(f"namespace Hashtree.Proofs.Avx2X8WBodyR{r}S\n")
    for j in range(lo, hi + 1):
        s = slices[j]
        a.append(f"theorem sliceS_{j} : sliceCheck prog 4 (m8P {r}) orcB {s['n']} (stripK8 {r} K{j}) "
                 f"(stripK8 {r} K{j + 1}) T{j} = true := by\n  decide +kernel\n")
    a.append(f"end Hashtree.Proofs.Avx2X8WBodyR{r}S\n")
    return "\n".join(a)


def emit_main2(r, ranges, slices):
    a = []
    for p in range(len(ranges)):
        a.append(f"import Hashtree.Proofs.Avx2X8WBodyR{r}S{p + 1}")
    a.append(f"import Hashtree.Proofs.Avx2X8WStrip{r}")
    a.append(HEADER)
    a.append("open Hashtree.Proofs.Avx2X8WStrip\n")
    a.append(f"""/-!
# The avx2_x8 body of a later pass, residue {r}

The 208 body slices `K2 .. K210` of a second or later pass: the cuts are stripped of the 40
spilled cells (`stripK8 {r}`), which the symbolic memory `m8P {r}` serves from its push list;
the first two cuts carry the loop-carried vector registers (`KHs {r}`, `KH3s {r}`;
`Avx2X8WStrip.stripFacts {r}`: `sliceV2s`, `sliceV3s`).  `bodyS_runW` composes them from the stripped
invariant head to the stripped `K210` (generated by `tools/avx_x8w.py`).
-/""")
    a.append(f"namespace Hashtree.Proofs.Avx2X8WBodyR{r}S\n")
    a.append("/-- The two replayed head cuts, read off the residue's kernel check. -/")
    a.append(f"theorem sliceV2s : sliceCheck prog 4 (m8P {r}) orcB {slices[2]['n']} (KHs {r}) (KH3s {r}) T2 = true :=")
    a.append(f"  (stripFacts {r} stripOk_{r}).2.1")
    a.append(f"theorem sliceV3s : sliceCheck prog 4 (m8P {r}) orcB {slices[3]['n']} (KH3s {r}) (stripK8 {r} K4) T3 = true :=")
    a.append(f"  (stripFacts {r} stripOk_{r}).2.2.1\n")
    a.append("/-! ## The environment chain of a later pass -/\n")
    a.append(f"def GS{FIRST} (env1 : Key → W32) : Key → W32 := env1")
    a.append(f"def GS3 (env1 : Key → W32) : Key → W32 := "
             f"envAbs (GS2 env1) (run prog 4 (m8P {r}) orcB {slices[2]['n']} (KHs {r}))")
    a.append(f"def GS4 (env1 : Key → W32) : Key → W32 := "
             f"envAbs (GS3 env1) (run prog 4 (m8P {r}) orcB {slices[3]['n']} (KH3s {r}))")
    for j in range(4, LAST + 1):
        s = slices[j]
        a.append(f"def GS{j + 1} (env1 : Key → W32) : Key → W32 := "
                 f"envAbs (GS{j} env1) (run prog 4 (m8P {r}) orcB {s['n']} (stripK8 {r} K{j}))")
    a.append("")
    nums = [slices[j]["n"] for j in range(FIRST, LAST + 1)]
    total = rsum(nums)
    a.append(f"""/-- **A later pass of the body, residue {r}.**  From the stripped invariant head to the
stripped `K210`, `BODYLEN` instructions, at any count `c ≥ 8`, over the push memory. -/
theorem bodyS_runW (env1 : Key → W32) (σ : Nat → Int) (mem0c : Addr Int → Cell W32 Int)
    (orcC : Nat → Bool) (h0 : Mem0Rel (GS{FIRST} env1) σ (m8P {r}) mem0c) (hge : 8 ≤ σ 2) :
    run prog 4 mem0c orcC BODYLEN (mapState (GS{FIRST} env1) σ (KHs {r})) =
      mapState (GS{LAST + 1} env1) σ (stripK8 {r} K{LAST + 1}) := by
  rw [show BODYLEN = ({total}) from rfl]
  have kq : MemKeyed (m8P {r}) := m8P_keyed_{r}
  have hm{FIRST} : Mem0Rel (GS{FIRST} env1) σ (m8P {r}) mem0c := h0""")
    for j in range(FIRST, LAST + 1):
        a.append(f"  have hm{j + 1} : Mem0Rel (GS{j + 1} env1) σ (m8P {r}) mem0c := "
                 f"mem0Rel_envAbs _ σ _ mem0c kq hm{j} _")
    a.append(f"  have r2 : run prog 4 mem0c orcC {slices[2]['n']} (mapState (GS2 env1) σ (KHs {r})) = "
             f"mapState (GS3 env1) σ (KH3s {r}) := "
             f"(slice_sound (GS2 env1) σ (m8P {r}) mem0c hm2 prog 4 orcB orcC {slices[2]['n']} (KHs {r}) (KH3s {r}) T2 "
             f"sliceV2s rfl (assumeOk_of σ (KH3s {r}) A0 rfl (asmge σ hge))).1")
    a.append(f"  have r3 : run prog 4 mem0c orcC {slices[3]['n']} (mapState (GS3 env1) σ (KH3s {r})) = "
             f"mapState (GS4 env1) σ (stripK8 {r} K4) := "
             f"(slice_sound (GS3 env1) σ (m8P {r}) mem0c hm3 prog 4 orcB orcC {slices[3]['n']} (KH3s {r}) (stripK8 {r} K4) T3 "
             f"sliceV3s rfl (assumeOk_of σ (stripK8 {r} K4) A0 rfl (asmge σ hge))).1")
    for j in range(4, LAST + 1):
        s = slices[j]
        a.append(f"  have r{j} : run prog 4 mem0c orcC {s['n']} (mapState (GS{j} env1) σ (stripK8 {r} K{j})) = "
                 f"mapState (GS{j + 1} env1) σ (stripK8 {r} K{j + 1}) := "
                 f"(slice_sound (GS{j} env1) σ (m8P {r}) mem0c hm{j} prog 4 orcB orcC {s['n']} (stripK8 {r} K{j}) "
                 f"(stripK8 {r} K{j + 1}) T{j} sliceS_{j} rfl "
                 f"(assumeOk_of σ (stripK8 {r} K{j + 1}) A0 rfl (asmge σ hge))).1")
    for j in range(FIRST, LAST):
        a.append(f"  rw [run_add, r{j}]")
    a.append(f"  exact r{LAST}\n")
    a.append(f"""/-- The memory relation carried along a later pass. -/
theorem bodyS_memW (env1 : Key → W32) (σ : Nat → Int) (mem0c : Addr Int → Cell W32 Int)
    (h0 : Mem0Rel (GS{FIRST} env1) σ (m8P {r}) mem0c) : Mem0Rel (GS{LAST + 1} env1) σ (m8P {r}) mem0c := by
  have kq : MemKeyed (m8P {r}) := m8P_keyed_{r}
  have hm{FIRST} : Mem0Rel (GS{FIRST} env1) σ (m8P {r}) mem0c := h0""")
    for j in range(FIRST, LAST + 1):
        a.append(f"  have hm{j + 1} : Mem0Rel (GS{j + 1} env1) σ (m8P {r}) mem0c := "
                 f"mem0Rel_envAbs _ σ _ mem0c kq hm{j} _")
    a.append(f"  exact hm{LAST + 1}\n")
    a.append(f"end Hashtree.Proofs.Avx2X8WBodyR{r}S\n")
    return "\n".join(a)


def main():
    if len(sys.argv) not in (2, 3) or sys.argv[1] not in ("0", "16"):
        print(__doc__, file=sys.stderr)
        sys.exit(2)
    r = int(sys.argv[1])
    pass2 = len(sys.argv) == 3 and sys.argv[2] == "--pass2"
    slices = read_slices()
    ranges = part_ranges()
    if pass2:
        lo2 = 4   # the first two cuts of a later pass are the replayed heads (Avx2X8WStrip)
        ranges = [(max(lo, lo2), hi) for (lo, hi) in ranges]
        for p, (lo, hi) in enumerate(ranges):
            path = os.path.join(PROOFS, f"Avx2X8WBodyR{r}S{p + 1}.lean")
            open(path, "w").write(emit_part2(r, p, lo, hi, slices))
            print("wrote", path, f"slices {lo}..{hi}")
        path = os.path.join(PROOFS, f"Avx2X8WBodyR{r}S.lean")
        open(path, "w").write(emit_main2(r, ranges, slices))
        print("wrote", path)
        return
    for p, (lo, hi) in enumerate(ranges):
        path = os.path.join(PROOFS, f"Avx2X8WBodyR{r}P{p + 1}.lean")
        open(path, "w").write(emit_part(r, p, lo, hi, slices))
        print("wrote", path, f"slices {lo}..{hi}")
    path = os.path.join(PROOFS, f"Avx2X8WBodyR{r}.lean")
    open(path, "w").write(emit_main(r, ranges, slices))
    print("wrote", path, "total", sum(slices[j]["n"] for j in range(FIRST, LAST + 1)))


if __name__ == "__main__":
    main()
