#!/usr/bin/env python3
"""Generate rv_insn.c: every modelled data instruction form (with each tested immediate) applied by
the real ISA (qemu) to edge-case and random 64-bit operands; prints `op imm a b result` lines
(hex) that `rvcheck --insn` recomputes with the model (tools/rv_insn_diff.sh compares).

    rv_insn_gen.py > rv_insn.c
"""
cases = []   # (op, imm field (hex string), asm template using %0 dst %1 a %2 b)
for op in ['sha256sum0', 'sha256sum1', 'sha256sig0', 'sha256sig1', 'rev8']:
    cases.append((op, 0, '%s %%0,%%1' % op))
for op in ['roriw', 'slliw', 'srliw', 'sraiw']:
    for n in range(32):
        cases.append((op, n, '%s %%0,%%1,%d' % (op, n)))
for op in ['srai', 'slli']:
    for n in range(64):
        cases.append((op, n, '%s %%0,%%1,%d' % (op, n)))
for op in ['addw', 'add', 'and', 'or', 'xor']:
    cases.append((op, 0, '%s %%0,%%1,%%2' % op))
for op in ['addi', 'andi']:
    for v in [0, 1, -1, -256, 2047, -2048, 0x555, -0x2ab, 64, -80]:
        cases.append((op, v & 0xfff, '%s %%0,%%1,%d' % (op, v)))
for v in [0, 1, 0x10, 0xff0, 0x7ffff, 0x80000, 0xfffff, 0x12345, 0x2, 0xabcde]:
    cases.append(('lui', v, 'lui %%0,0x%x' % v))

# memory forms: `lwu imm`: load from a buffer holding a (8 bytes LE); `swld imm`: sw b at imm into
# that buffer, then ld 0; `sdld 0`: sd b, then ld
MEM = []
for off in [0, 4, 1, 2, 3]:
    MEM.append(('lwu', off, 'lwu %%0,%d(%%1)' % off))
for off in [0, 4, 2]:
    MEM.append(('swld', off, 'sw %%2,%d(%%1)\\n\\tld %%0,0(%%1)' % off))
MEM.append(('sdld', 0, 'sd %2,0(%1)\\n\\tld %0,0(%1)'))
print('/* generated by rv_insn_gen.py */')
print('typedef unsigned long u64;')
for i, (op, imm, t) in enumerate(cases):
    print('static u64 f%d(u64 a, u64 b) { u64 r; asm volatile("%s" : "=r"(r) : "r"(a), "r"(b)); return r; }' % (i, t))
for j, (op, imm, t) in enumerate(MEM):
    i = len(cases) + j
    print('static u64 f%d(u64 a, u64 b) { static u64 m[2]; m[0] = a; m[1] = 0; u64 r; '
          'asm volatile("%s" : "=&r"(r) : "r"(m), "r"(b) : "memory"); return r; }' % (i, t))
cases += MEM
print('static u64 (*const fns[])(u64, u64) = {%s};' % ', '.join('f%d' % i for i in range(len(cases))))
print('static const char *const names[] = {%s};' % ', '.join('"%s %x"' % (op, imm) for op, imm, _ in cases))
print('#define NCASES %d' % len(cases))
print(r'''
static long sys3(long n, long a, long b, long c) {
    register long a7 asm("a7") = n; register long a0 asm("a0") = a;
    register long a1 asm("a1") = b; register long a2 asm("a2") = c;
    asm volatile("ecall" : "+r"(a0) : "r"(a7), "r"(a1), "r"(a2) : "memory"); return a0;
}
static char buf[1 << 16]; static long bl;
static void flush(void) { sys3(64, 1, (long)buf, bl); bl = 0; }
static void ch(char c) { buf[bl++] = c; if (bl == sizeof buf) flush(); }
static void str(const char *s) { while (*s) ch(*s++); }
static void hex(u64 v) { for (int i = 60; i >= 0; i -= 4) ch("0123456789abcdef"[(v >> i) & 15]); }
static const u64 edge[] = {0, 1, 0x7fffffffUL, 0x80000000UL, 0xffffffffUL, 0xffffffff80000000UL,
    0x8000000000000000UL, 0xffffffffffffffffUL, 0x7fffffffffffffffUL, 0x123456789abcdef0UL,
    0x00000000deadbeefUL, 0xffffffffdeadbeefUL, 0xdeadbeef00000000UL, 0x0000000100000000UL};
long cmain(void) {
    u64 x = 0x243f6a8885a308d3UL;
    for (int c = 0; c < NCASES; c++) {
        for (int j = 0; j < 14 + 36; j++) {
            u64 a, b;
            x = x * 6364136223846793005UL + 1442695040888963407UL; a = x;
            x = x * 6364136223846793005UL + 1442695040888963407UL; b = x;
            if (j < 14) { a = edge[j]; b = edge[13 - j]; }
            if (j >= 40) { a = (u64)(long)(int)a; b = (u64)(long)(int)b; }   /* sign-extended operands */
            str(names[c]); ch(' '); hex(a); ch(' '); hex(b); ch(' '); hex(fns[c](a, b)); ch('\n');
        }
    }
    flush();
    return 0;
}
asm(".globl _start\n_start:\n.option push\n.option norelax\n  la gp, __global_pointer$\n.option pop\n"
    "  andi sp, sp, -16\n  call cmain\n  li a7, 93\n  ecall\n");''')
