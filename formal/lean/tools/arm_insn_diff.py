#!/usr/bin/env python3
"""Per-instruction differential test of the AArch64 model against the real instruction.

    arm_insn_diff.py <out.lean> <out.c>

Writes `Hashtree/Asm/ArmInsnTests.lean` (the test instructions, translated by the same
`arm_to_lean.translate` as the kernels) and a C program that, for every test, executes the
instruction natively on random register and memory contents and prints one vector line per
trial:

    idx  v0..v7 (32 hex words)  x2..x5 (8: lo, hi)  input buffer (16 words)
         v0..v7 after  x2..x5 after  output buffer after (16 words)  x0 change  x1 change

Before the instruction: x0 = output buffer (64 zero bytes), x1 = input buffer (64 random
bytes), x7 = 64.  `armcheck --insn <vectors>` runs the model on the same inputs and compares.
Build/run (on the VM):

    aarch64-linux-gnu-gcc -O1 -static -nostdlib -ffreestanding -fno-builtin -march=armv8-a+crypto -I tools arm_insn.c -o arm_insn
    qemu-aarch64-static -cpu max ./arm_insn 200 > vectors.txt
"""
