def lean_terms():
    out = []
    for t in TESTS:
        mn, ops = arm_to_lean.parse_insn(t)
        out.append(arm_to_lean.translate(mn, ops, None, None, None))
    return out


def write_lean(path, terms):
    with open(path, 'w') as f:
        f.write('import Hashtree.Asm.Arm\n\n')
        f.write('/-! Generated by tools/arm_insn_diff.py: the instructions of the per-instruction\n'
                'differential test (`armcheck --insn`), translated by `tools/arm_to_lean.py`. -/\n\n')
        f.write('namespace Hashtree.Asm.Arm\n\n')
        f.write('set_option maxRecDepth 100000 in\n')
        f.write('/-- (assembler text, model instruction) -/\n')
        f.write('def insnTests : Array (String × Instr) := #[\n')
        for k, (t, term) in enumerate(zip(TESTS, terms)):
            sep = ',' if k + 1 < len(TESTS) else ''
            f.write('  ("%s", %s)%s  -- %d\n' % (t, term, sep, k))
        f.write(']\n\nend Hashtree.Asm.Arm\n')


C_HEAD = r'''#include "arm_rt.h"

struct st { uint32_t v[32]; uint64_t x[4]; uint64_t x0, x1; };
static uint8_t inbuf[64] __attribute__((aligned(16)));
static uint8_t outbuf[64] __attribute__((aligned(16)));
static uint64_t rs = 0x9e3779b97f4a7c15ull;
static uint64_t rnd(void) { rs ^= rs >> 12; rs ^= rs << 25; rs ^= rs >> 27; return rs * 0x2545f4914f6cdd1dull; }

#define PRE "ld1 {v0.4s-v3.4s}, [%0], #64\n\tld1 {v4.4s-v7.4s}, [%0], #64\n\tldp x2, x3, [%0], #16\n\t" \
  "ldp x4, x5, [%0], #16\n\tldp x0, x1, [%0]\n\tsub %0, %0, #160\n\tmov x7, #64\n\t"
#define POST "\n\tst1 {v0.4s-v3.4s}, [%0], #64\n\tst1 {v4.4s-v7.4s}, [%0], #64\n\tstp x2, x3, [%0], #16\n\t" \
  "stp x4, x5, [%0], #16\n\tstp x0, x1, [%0]\n\t"
#define CLOB "x0", "x1", "x2", "x3", "x4", "x5", "x6", "x7", "v0", "v1", "v2", "v3", "v4", "v5", "v6", "v7", "memory"
'''

C_MAIN = r'''
int main(int argc, char **argv) {
  int trials = argc > 1 ? atoi_(argv[1]) : 100;
  for (int t = 0; t < NTESTS; t++)
    for (int k = 0; k < trials; k++) {
      struct st s, r;
      for (int i = 0; i < 32; i++) s.v[i] = (uint32_t)rnd();
      for (int i = 0; i < 4; i++) s.x[i] = rnd();
      for (int i = 0; i < 64; i++) inbuf[i] = (uint8_t)rnd();
      memset(outbuf, 0, 64);
      s.x0 = (uint64_t)outbuf; s.x1 = (uint64_t)inbuf;
      r = s;
      uint32_t in32[16]; memcpy(in32, inbuf, 64);
      FUNCS[t](&r);
      uint32_t out32[16]; memcpy(out32, outbuf, 64);
      odec(t);
      for (int i = 0; i < 32; i++) { oc(' '); ohex(s.v[i]); }
      for (int i = 0; i < 4; i++) { oc(' '); ohex((uint32_t)s.x[i]); oc(' '); ohex((uint32_t)(s.x[i] >> 32)); }
      for (int i = 0; i < 16; i++) { oc(' '); ohex(in32[i]); }
      for (int i = 0; i < 32; i++) { oc(' '); ohex(r.v[i]); }
      for (int i = 0; i < 4; i++) { oc(' '); ohex((uint32_t)r.x[i]); oc(' '); ohex((uint32_t)(r.x[i] >> 32)); }
      for (int i = 0; i < 16; i++) { oc(' '); ohex(out32[i]); }
      oc(' '); odec((long long)(r.x0 - (uint64_t)outbuf)); oc(' '); odec((long long)(r.x1 - (uint64_t)inbuf)); oc('\n');
    }
  return 0;
}
'''


def write_c(path):
    with open(path, 'w') as f:
        f.write(C_HEAD)
        for k, t in enumerate(TESTS):
            f.write('static void t%d(struct st *p) { /* %s */\n' % (k, t))
            f.write('  __asm__ volatile(PRE "%s" POST : "+r"(p) : : CLOB);\n}\n' % t)
        f.write('#define NTESTS %d\n' % len(TESTS))
        f.write('static void (*FUNCS[])(struct st *) = {%s};\n' % ', '.join('t%d' % k for k in range(len(TESTS))))
        f.write(C_MAIN)


def main():
    terms = lean_terms()
    write_lean(sys.argv[1], terms)
    write_c(sys.argv[2])


if __name__ == '__main__':
    main()
